"""
polarization.py — CMB E-mode polarization power spectrum (basic).

CMB polarization is generated by the photon quadrupole Theta_2 at recombination.
The polarization source function is:

  S_E(k, tau) = g(tau) * sqrt(6)/10 * Theta_2(k, tau)

For the instantaneous recombination approximation:
  C_l^EE = (4 pi) int dk/k P_R(k) * |Delta_l^E(k)|^2

where Delta_l^E uses the E-mode transfer function with spin-2 projection:
  Delta_l^E(k) = sqrt(6)/10 * Theta_2(k, tau_rec) * epsilon_l(x)

with x = k * D_A, and:
  epsilon_l(x) = sqrt((l+2)!/(l-2)!) / x^2 * j_l(x)

For l >> 1, epsilon_l(x) ~ (l^2/x^2) * j_l(x).

TIGHT-COUPLING APPROXIMATION for Theta_2:
  When |kappa_dot| >> k (tight coupling), the quadrupole is suppressed:
    Theta_2 ~ (8/15) * (k / |kappa_dot|) * Theta_1

  This comes from the Boltzmann hierarchy:
    0 = k/5 * (2 Theta_1 - 3 Theta_3) - (9/10) * |kappa_dot| * Theta_2
  and Theta_3 << Theta_1, giving:
    Theta_2 = (2k)/(5 * (9/10) * |kappa_dot|) * Theta_1
            = (4/9) * k * Theta_1 / |kappa_dot|

  But more precisely, the polarization-generating quadrupole in the
  full treatment has a factor of (8/15) from the angular integration
  of Thomson scattering.

IMPLEMENTATION:
  1. If HiRes solver result is available (has Theta_2 from the hierarchy):
     use Theta_2 directly.
  2. Otherwise, estimate Theta_2 from the tight-coupling formula:
     Theta_2 ~ (4/9) * k * Theta_1 / |kappa_dot(tau_rec)|
  This gives the correct SHAPE but approximate AMPLITUDE.

Author: Sheng-Kai Huang, 2026
"""
import numpy as np
import mlx.core as mx
