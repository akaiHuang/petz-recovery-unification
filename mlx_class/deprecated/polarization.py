# Plotting
# ============================================================================

def plot_cl_ee(ell_values, Dl_EE, out_path=None, Dl_TT=None,
               ell_TT=None, ell_max=2500):
    """
    Generate E-mode polarization power spectrum plot.

    Parameters
    ----------
    ell_values : array
        Multipole values.
    Dl_EE : array
        D_l^EE in muK^2.
    out_path : str or None
        Save path.
    Dl_TT : array or None
        TT spectrum for comparison (same ell grid or separate).
    ell_TT : array or None
        ell values for TT (if different from EE).
    ell_max : int
        Maximum ell for plot.
    """
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import os

    if Dl_TT is not None:
        fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    else:
        fig, axes = plt.subplots(1, 1, figsize=(8, 6))
        axes = [axes]

    # EE spectrum
    ax = axes[0]
    mask = ell_values <= ell_max
    ax.semilogy(ell_values[mask], Dl_EE[mask], 'r-', lw=1.5,
                label=r'$D_\ell^{EE}$ (mlx\_class)')
    ax.set_xlabel('Multipole l', fontsize=13)
    ax.set_ylabel(r'$D_\ell^{EE}$ [$\mu K^2$]', fontsize=13)
    ax.set_title('CMB E-mode Polarization', fontsize=14)
    ax.legend(fontsize=11)
    ax.set_xlim(2, ell_max)

    # Peak finding
    from scipy.signal import find_peaks
    from scipy.interpolate import interp1d as interp

    l_full = np.arange(2, min(ell_max + 1, int(ell_values[mask][-1]) + 1))
    if len(ell_values[mask]) > 10:
        f = interp(ell_values[mask], Dl_EE[mask], kind='cubic',
                   fill_value='extrapolate')
        Dl_full = np.maximum(f(l_full), 0.0)
        peaks, _ = find_peaks(Dl_full, distance=60, prominence=0.1 * np.max(Dl_full))
        if len(peaks) > 0:
            colors = ['blue', 'green', 'orange', 'purple', 'brown']
            for i, p in enumerate(peaks[:5]):
                ax.plot(l_full[p], Dl_full[p], 'o', color=colors[i % 5], ms=8)
                ax.annotate(f'l={l_full[p]}',
                            (l_full[p], Dl_full[p] * 1.3),
                            fontsize=9, ha='center', color=colors[i % 5])

    # TT comparison
    if Dl_TT is not None and len(axes) > 1:
        ax2 = axes[1]
        if ell_TT is None:
            ell_TT = ell_values
        mask_TT = ell_TT <= ell_max
        ax2.plot(ell_TT[mask_TT], Dl_TT[mask_TT], 'b-', lw=1.2,
                 label=r'$D_\ell^{TT}$')
        ax2.plot(ell_values[mask], Dl_EE[mask], 'r-', lw=1.2,
                 label=r'$D_\ell^{EE}$')
        ax2.set_xlabel('Multipole l', fontsize=13)
        ax2.set_ylabel(r'$D_\ell$ [$\mu K^2$]', fontsize=13)
        ax2.set_title('TT vs EE Comparison', fontsize=14)
        ax2.set_yscale('log')
        ax2.legend(fontsize=11)
        ax2.set_xlim(2, ell_max)

    plt.tight_layout()

    if out_path is None:
        out_dir = os.path.dirname(os.path.abspath(__file__))
        out_path = os.path.join(out_dir, 'cl_ee_polarization.png')

    plt.savefig(out_path, dpi=150)
    plt.close()
    print(f"[EE] Plot saved: {out_path}")

    return out_path


