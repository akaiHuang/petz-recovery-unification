# ============================================================================
# E-mode angular projection factor: epsilon_l(x) = sqrt((l+2)!/(l-2)!) / x^2 * j_l(x)
# ============================================================================

def _epsilon_l(ell, x_arr):
    """
    Spin-2 Bessel projection factor for E-mode polarization.

    epsilon_l(x) = sqrt((l+2)!/(l-2)!)) / x^2 * j_l(x)

    For l >= 2:
      sqrt((l+2)!/(l-2)!) = sqrt((l-1)*l*(l+1)*(l+2))

    Handles x=0 gracefully (epsilon_l -> 0).
    """
    l = int(ell)
    if l < 2:
        return np.zeros_like(x_arr)

    # Prefactor: sqrt((l+2)!/(l-2)!) = sqrt((l-1)*l*(l+1)*(l+2))
    prefactor = np.sqrt(float((l - 1) * l * (l + 1) * (l + 2)))

    jl = spherical_jn(l, x_arr)

    # Avoid division by zero: for x << 1, epsilon_l ~ 0 anyway
    x_safe = np.where(np.abs(x_arr) < 1e-10, 1e-10, x_arr)
    result = prefactor * jl / (x_safe ** 2)

    # Zero out truly small x
    result = np.where(np.abs(x_arr) < 1e-10, 0.0, result)
    return result


# ============================================================================
# Extract Theta_2 from solver result
# ============================================================================

def _get_theta2_from_result(result, solver_type):
    """
    Extract Theta_2(k, tau_rec) from a solver result.

    For 'hires': Theta_2 is solved directly in the photon hierarchy.
    For others: estimate from tight-coupling formula.
    """
    bg = result.bg

    if solver_type == 'hires':
        # HiRes solver has Theta_2 directly
        Theta_0, Phi, Psi, v_b, Theta_2 = result.source_at_recombination()
        k_arr = result.k_arr
        return k_arr, Theta_2, True

    # For TCA-based solvers: estimate Theta_2 from the tight-coupling formula
    # Theta_2 ~ (4/9) * k * Theta_1 / |kappa_dot(tau_rec)|
    k_arr = result.k_arr
    y_np = np.array(result.y if hasattr(result, 'y') else result.y_tca)

    if solver_type == 'neutrino':
        from .perturbations_neutrino import IDX_THETA_1
        Theta_1 = y_np[:, IDX_THETA_1]
    elif solver_type == 'implicit':
        from .perturbations_implicit import TCA_THETA_1
        Theta_1 = y_np[:, TCA_THETA_1]
    elif solver_type == 'explicit':
        from .perturbations import TCA_THETA_1
        Theta_1 = y_np[:, TCA_THETA_1]
    else:
        raise ValueError(f"Unknown solver_type: {solver_type}")

    # kappa_dot at tau_rec
    kappa_dot_rec = bg.kappa_dot_at_tau(np.array([bg.tau_rec]))[0]
    abs_kappa_dot = np.abs(kappa_dot_rec)

    # Tight-coupling estimate for Theta_2
    # Theta_2 = (4/9) * k * Theta_1 / |kappa_dot|
    if abs_kappa_dot > 1e-10:
        Theta_2 = (4.0 / 9.0) * k_arr * Theta_1 / abs_kappa_dot
    else:
        # kappa_dot ~ 0 means fully decoupled; Theta_2 is large
        # Use the free-streaming limit: Theta_2 ~ 0.1 * Theta_0
        from .perturbations_implicit import TCA_THETA_0
        Theta_0 = y_np[:, TCA_THETA_0]
        Theta_2 = 0.1 * Theta_0

    # Apply Silk damping
    silk = np.exp(-(k_arr / bg.k_D) ** 2)
    Theta_2 = Theta_2 * silk

    return k_arr, Theta_2, False


# ============================================================================
# E-mode C_l^EE computation
# ============================================================================

def compute_cl_ee(result, ell_values, solver_type='implicit'):
    """
    Compute the E-mode polarization power spectrum C_l^EE.

    C_l^EE = (4 pi) int dk/k P_R(k) * |Delta_l^E(k)|^2

    where Delta_l^E(k) = (sqrt(6)/10) * Theta_2(k) * epsilon_l(k*D_A)

    Parameters
    ----------
    result : solver result
        Output from any Boltzmann solver.
    ell_values : array
        Multipole values (must be >= 2).
    solver_type : str
        'implicit', 'neutrino', 'hires', 'explicit'

    Returns
    -------
    ell_values : array
    Cl_EE : array
        C_l^EE (dimensionless).
    Dl_EE : array
        l(l+1) C_l^EE / (2 pi) in muK^2.
    """
    t0 = time.time()

    bg = result.bg
    D_A = bg.D_A

    # Get Theta_2
    k_arr, Theta_2, is_exact = _get_theta2_from_result(result, solver_type)
    source_label = "exact (hierarchy)" if is_exact else "estimated (TCA)"
    print(f"[EE] Theta_2 source: {source_label}")
    print(f"[EE] Theta_2 range: [{np.min(Theta_2):.4e}, {np.max(Theta_2):.4e}]")

    # Polarization source: S_E = sqrt(6)/10 * Theta_2
    S_E = np.sqrt(6.0) / 10.0 * Theta_2

    # Filter to ell >= 2 only
    ell_values = np.asarray(ell_values, dtype=int)
    ell_values = ell_values[ell_values >= 2]
    N_ell = len(ell_values)
    N_k = len(k_arr)

    # Bessel arguments
    x_arr = k_arr * D_A

    # Primordial power spectrum
    P_R = A_s * (k_arr / k_pivot) ** (n_s - 1.0)

    # Compute epsilon_l table
    print(f"[EE] Computing epsilon_l for {N_ell} ells...")
    t_bessel = time.time()
    eps_table = np.zeros((N_ell, N_k), dtype=np.float32)
    for il, ell in enumerate(ell_values):
        eps_table[il] = _epsilon_l(ell, x_arr)
    print(f"[EE] Bessel: {time.time() - t_bessel:.2f}s")

    # Transfer function: Delta_l^E(k) = S_E(k) * epsilon_l(k * D_A)
    Delta_l_E = S_E[None, :] * eps_table  # (N_ell, N_k)

    # C_l = 4 pi int dk/k P_R |Delta_l|^2
    integrand = (P_R[None, :] * Delta_l_E ** 2).astype(np.float32)
    lnk = np.log(k_arr)
    dlnk = np.diff(lnk).astype(np.float32)

    # GPU integration
    integrand_gpu = mx.array(integrand)
    dlnk_gpu = mx.array(dlnk)
    mid = 0.5 * (integrand_gpu[:, :-1] + integrand_gpu[:, 1:])
    Cl_gpu = 4.0 * np.pi * mx.sum(mid * dlnk_gpu[None, :], axis=1)
    mx.eval(Cl_gpu)

    Cl_EE = np.maximum(np.array(Cl_gpu), 0.0)

    # D_l in muK^2
    ell_f = ell_values.astype(float)
    Dl_EE = ell_f * (ell_f + 1.0) * Cl_EE / (2.0 * np.pi) * (T_CMB * 1e6) ** 2

    t_total = time.time() - t0
    print(f"[EE] C_l^EE computed in {t_total:.2f}s")
    print(f"[EE] D_l^EE range: [{np.min(Dl_EE):.2e}, {np.max(Dl_EE):.2e}] uK^2")

    return ell_values, Cl_EE, Dl_EE


