def _test_polarization():
    """
    Test the E-mode polarization computation.
    1. Verify epsilon_l normalization
    2. Compute C_l^EE
    3. Check peak structure (EE peaks between TT peaks)
    """
    print("=" * 70)
    print("TEST: CMB E-mode Polarization C_l^EE")
    print("=" * 70)

    from .background import Background

    # Background
    bg = Background(khronon=False)
    bg.solve()

    # k-grid
    k_arr = np.geomspace(5e-4, 0.35, 500).astype(np.float32)

    # Solve with implicit solver
    from .perturbations_implicit import ImplicitBoltzmannSolver
    solver = ImplicitBoltzmannSolver(bg, k_arr)
    result = solver.solve()

    # Test 1: epsilon_l
    print("\n--- Test 1: epsilon_l projection ---")
    x_test = np.linspace(0.1, 100, 1000)
    eps2 = _epsilon_l(2, x_test)
    eps10 = _epsilon_l(10, x_test)
    eps100 = _epsilon_l(100, x_test)
    print(f"  epsilon_2 max: {np.max(np.abs(eps2)):.4f}")
    print(f"  epsilon_10 max: {np.max(np.abs(eps10)):.4f}")
    print(f"  epsilon_100 max: {np.max(np.abs(eps100)):.4f}")
    if np.all(np.isfinite(eps2)) and np.all(np.isfinite(eps100)):
        print("  PASS: All finite")
    else:
        print("  FAIL: Non-finite values")

    # Test 2: C_l^EE
    print("\n--- Test 2: C_l^EE computation ---")
    ell_values = np.unique(np.concatenate([
        np.arange(2, 30, 1), np.arange(30, 100, 2),
        np.arange(100, 500, 4), np.arange(500, 1500, 8),
        np.arange(1500, 2501, 12),
    ])).astype(int)

    ell_ee, Cl_EE, Dl_EE = compute_cl_ee(result, ell_values, solver_type='implicit')
    print(f"  D_l^EE range: [{np.min(Dl_EE):.4f}, {np.max(Dl_EE):.4f}] uK^2")

    # Test 3: Peak structure
    print("\n--- Test 3: EE peak structure ---")
    from scipy.signal import find_peaks
    from scipy.interpolate import interp1d

    l_full = np.arange(2, 2501)
    f = interp1d(ell_ee, Dl_EE, kind='cubic', fill_value='extrapolate')
    Dl_full = np.maximum(f(l_full), 0.0)
    peaks, _ = find_peaks(Dl_full, distance=60, prominence=0.1 * np.max(Dl_full))
    if len(peaks) > 0:
        peak_ls = l_full[peaks[:5]]
        peak_Ds = Dl_full[peaks[:5]]
        print(f"  EE peaks at l = {peak_ls}")
        print(f"  Heights = {[f'{d:.2f}' for d in peak_Ds]} uK^2")
        # EE peaks should be approximately between TT peaks
        # First EE peak ~ 140 (between l=0 and l=220 TT peaks)
        # Second EE peak ~ 400 (between TT peaks at 220 and 540)
    else:
        print("  WARNING: No peaks found")

    # Test 4: Stability
    print("\n--- Test 4: Stability ---")
    has_nan = np.any(np.isnan(Dl_EE))
    has_inf = np.any(np.isinf(Dl_EE))
    has_neg = np.any(Dl_EE < 0)
    print(f"  NaN: {has_nan}, Inf: {has_inf}, Negative: {has_neg}")
    if not (has_nan or has_inf):
        print("  PASS: All finite")
    else:
        print("  FAIL!")

    # Plot
    print("\n--- Generating plot ---")
    # Also compute TT for comparison
    from .spectra import compute_cl
    Theta_0, Phi, v_b = result.source_at_recombination()
    source_SW = Theta_0 + Phi
    _, _, Dl_TT = compute_cl(source_SW, k_arr, ell_values, bg.D_A)

    plot_cl_ee(ell_ee, Dl_EE, Dl_TT=Dl_TT, ell_TT=ell_values)

    print("\n" + "=" * 70)
    print("E-MODE POLARIZATION TEST COMPLETE")
    print("=" * 70)

    return ell_ee, Dl_EE


if __name__ == '__main__':
    _test_polarization()
